def build_station_lines(write: bool = True) -> pd.DataFrame:
    rows = []
    for code, (name, seq) in LINES.items():
        for i, s in enumerate(seq.split(), 1):
            rows.append({"line": code, "line_name": name, "seq": i, "station": s})
    df = pd.DataFrame(rows)
    main_line = df["line"].str.split("-").str[0]
    nl = main_line.groupby(df["station"]).nunique()
    df["n_lines"] = df["station"].map(nl)
    df["is_transfer"] = (df["n_lines"] > 1).astype(int)
    df["panel_stations"] = df["station"].map(lambda s: ";".join(TWINS.get(s, [s])))
    if write:
        df.to_csv(EXTERNAL / "station_line_seq.csv", index=False)
    return df


def load_station_lines() -> pd.DataFrame:
    f = EXTERNAL / "station_line_seq.csv"
    return pd.read_csv(f) if f.exists() else build_station_lines()


def graph(stations: list[str]):
    """Return (panel->node map, node adjacency dict, node->lines)."""
    sl = load_station_lines()
    p2n = {}
    for _, r in sl.drop_duplicates("station").iterrows():
        for p in r["panel_stations"].split(";"):
            p2n[p] = r["station"]
    missing = [s for s in stations if s not in p2n]
    if missing:
        raise ValueError(f"stations missing from station_line_seq.csv: {missing}")
    adj: dict[str, set] = {}
    for _, g in sl.sort_values(["line", "seq"]).groupby("line"):
        s = g["station"].tolist()
        for a, b in zip(s[:-1], s[1:]):
            adj.setdefault(a, set()).add(b)
            adj.setdefault(b, set()).add(a)
    lines = sl.assign(ml=sl["line"].str.split("-").str[0]).groupby("station")["ml"].agg(set).to_dict()
    return p2n, adj, lines


def hop_distance(adj: dict, src: str) -> dict:
    d, q = {src: 0}, deque([src])
    while q:
        u = q.popleft()
        for v in adj[u]:
            if v not in d:
                d[v] = d[u] + 1
                q.append(v)
    return d


def neighbour_matrices(stations: list[str]):
    """Station x station 0/1 matrices: twins (same node), 1 hop, 2 hops, same line."""
    p2n, adj, lines = graph(stations)
    n = len(stations)
    M = {k: np.zeros((n, n)) for k in ("nb0", "nb1", "nb2", "line")}
    dist = {node: hop_distance(adj, node) for node in set(p2n[s] for s in stations)}
    for i, a in enumerate(stations):
        for j, b in enumerate(stations):
            if i == j:
                continue
            na, nb = p2n[a], p2n[b]
            dd = dist[na].get(nb, 99)
            if dd == 0:
                M["nb0"][i, j] = 1
            elif dd == 1:
                M["nb1"][i, j] = 1
            elif dd == 2:
                M["nb2"][i, j] = 1
            if lines[na] & lines[nb]:
                M["line"][i, j] = 1
    return M


def od_probs(stations: list[str], train_end: str = TRAIN_END, train_start_ym: str | None = None) -> np.ndarray:
    """p[h, o, d] = share of trips entering at o in hour-of-day h that go to d (training months)."""
    od = pd.read_parquet(PROCESSED / "od_hourprofile_monthly.parquet")
    end_ym = pd.Timestamp(train_end).strftime("%Y%m")
    od = od[od["ym"] <= end_ym]
    if train_start_ym:
        od = od[od["ym"] >= train_start_ym]
    if od.empty:
        raise ValueError(f"no OD months on or before {end_ym}")
    for c in ("origin", "dest"):
        od[c] = od[c].astype(str).str.strip().replace(RENAME)
    idx = {s: i for i, s in enumerate(stations)}
    od = od[od["origin"].isin(idx) & od["dest"].isin(idx)]
    g = od.groupby(["hour", "origin", "dest"])["trips"].sum().reset_index()
    n = len(stations)
    P = np.zeros((24, n, n))
    P[g["hour"].to_numpy(int), g["origin"].map(idx).to_numpy(), g["dest"].map(idx).to_numpy()] = g["trips"]
    rs = P.sum(2, keepdims=True)
    return np.divide(P, rs, out=np.zeros_like(P), where=rs > 0)


def _hist_avg(panel_wide: pd.DataFrame, hol: np.ndarray, train_mask: np.ndarray) -> np.ndarray:
    """HA[t, s] = training mean of the series at (station, day-type(t), hour(t))."""
    hour = panel_wide.index.hour.to_numpy()
    key = hol.astype(int) * 24 + hour
    X = panel_wide.to_numpy(float)
    tab = np.zeros((48, X.shape[1]))
    for k in range(48):
        m = (key == k) & train_mask
        if m.any():
            tab[k] = X[m].mean(0)
    return tab[key], tab


def spatial_features(panel: pd.DataFrame, h: int = 1, train_end: str = TRAIN_END,
                     od_start_ym: str | None = None) -> pd.DataFrame:
    """Long frame (ts=origin, station, spatial features at t) in the panel's (station, ts) order."""
    sys.path.insert(0, str(Path(__file__).parent))
    from features import load_calendar
    stations = list(panel["station"].cat.categories)
    E = panel.pivot(index="ts", columns="station", values="entries").reindex(columns=stations)
    X = panel.pivot(index="ts", columns="station", values="exits").reindex(columns=stations)
    ts = E.index
    cal = load_calendar().set_index("date")["is_holiday"]
    hol = ts.normalize().map(cal).fillna(False).to_numpy(bool)
    tgt = ts + pd.Timedelta(hours=h)
    hol_t = tgt.normalize().map(cal).fillna(False).to_numpy(bool)
    trm = np.asarray(ts <= pd.Timestamp(train_end))
    e, x = E.to_numpy(float), X.to_numpy(float)
    ha_e, tab_e = _hist_avg(E, hol, trm)
    ha_e_tgt = tab_e[hol_t.astype(int) * 24 + tgt.hour.to_numpy()]

    M = neighbour_matrices(stations)
    feats = {}
    tot = e + x
    feats["nb0_total"] = tot @ M["nb0"].T
    for k in ("nb1", "nb2"):
        A = M[k].T
        feats[f"{k}_entries"] = e @ A
        feats[f"{k}_exits"] = x @ A
        feats[f"{k}_anom"] = (e @ A + 50) / (ha_e @ A + 50)
    lag1 = np.vstack([np.full((1, e.shape[1]), np.nan), e[:-1]])
    feats["nb1_entries_l1"] = lag1 @ M["nb1"].T
    feats["line_entries"] = e @ M["line"].T
    feats["line_anom"] = (e @ M["line"].T + 100) / (ha_e @ M["line"].T + 100)
    feats["net_entries"] = np.repeat(e.sum(1, keepdims=True), e.shape[1], 1)
    feats["net_anom"] = np.repeat(((e.sum(1) + 100) / (ha_e.sum(1) + 100))[:, None], e.shape[1], 1)

    P = od_probs(stations, train_end, od_start_ym)
    hr, hr_t = ts.hour.to_numpy(), tgt.hour.to_numpy()
    a = np.clip((e + 10) / (ha_e + 10), 0, 5)            # origin anomaly at t
    e_next = a * ha_e_tgt                                  # expected entries at t+h per origin
    od_t, od_n = np.zeros_like(e), np.zeros_like(e)
    for hh in range(24):
        m = hr == hh
        od_t[m] = e[m] @ P[hh]
        m2 = hr_t == hh
        od_n[m2] = e_next[m2] @ P[hh]
    feats["od_exp_t"] = od_t
    feats["od_exp_next"] = od_n
    feats["od_ratio_t"] = (x + 10) / (od_t + 10)

    out = pd.DataFrame({"ts": np.tile(ts.to_numpy(), len(stations)),
                        "station": pd.Categorical(np.repeat(stations, len(ts)), categories=stations)})
    for k, v in feats.items():
        out[k] = v.T.ravel().astype("float32")
    return out


def add_relative(fr: pd.DataFrame) -> pd.DataFrame:
    """Scale-free versions for the scaled model (divide by the station's 168h mean of the target)."""
    for c in ("od_exp_next", "od_exp_t", "nb0_total"):
        if c in fr:
            fr[f"{c}_rel"] = fr[c] / fr["scale"]
    return fr


# --------------------------------------------------------------------------- ablation
def main():
    import importlib
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    lib = importlib.import_module("40_crowd_lib")
    from features import load_panel
    from metrics import reg_metrics
    from plotting import plt

    sl = build_station_lines()
    print(f"station_line_seq.csv: {sl.station.nunique()} physical stations, {sl.line.nunique()} line segments, "
          f"{sl[sl.is_transfer == 1].station.nunique()} transfer stations")
    panel = load_panel()
    configs = [(1, "base"), (1, "+neighbour"), (1, "+OD"), (1, "+all"), (2, "base"), (2, "+all")]
    if a.quick:
        configs = [(1, "base"), (1, "+all")]
    rows = []
    for target in ("entries", "exits"):
        for h in sorted({c[0] for c in configs}):
            fr = add_relative(lib.target_frame(panel, target, h, spatial=True))
            tr, va, te = lib.split(fr)
            base = lib.base_cols(fr)
            sp = lib.spatial_cols(fr)
            sets = {"base": base, "+neighbour": base + [c for c in sp if not c.startswith("od_")],
                    "+OD": base + [c for c in sp if c.startswith("od_")], "+all": base + sp}
            for hh, name in configs:
                if hh != h:
                    continue
                cols = sets[name]
                m = lib.fit_scaled_reg(tr, va, cols)
                p = lib.pred_scaled(m, te, cols)
                r = {"target": target, "horizon": h, "features": name, "n_features": len(cols),
                     **reg_metrics(te.y, p, te), "best_iter": m.best_iteration}
                rows.append(r)
                print(r, flush=True)
                if name == "+all" and h == 1:
                    imp = pd.Series(m.feature_importance("gain"), index=cols)
                    (imp / imp.sum()).sort_values(ascending=False).round(4).to_csv(
                        RESULTS / f"spatial_importance_h1_{target}.csv", header=["gain_share"])
    res = pd.DataFrame(rows)
    b = res[res.features == "base"].set_index(["target", "horizon"])["MAE"]
    res["MAE_change_vs_base_%"] = [round(100 * (r.MAE / b[(r.target, r.horizon)] - 1), 2) for r in res.itertuples()]
    res.to_csv(RESULTS / "spatial_ablation.csv", index=False)
    (RESULTS / "spatial_ablation.md").write_text(
        "# 空間特徵消融（LightGBM-scaled，測試集 2026-09）\n\n" + lib.to_md(res) + "\n", encoding="utf-8")
    print(res.to_string(index=False))

    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6), sharey=False)
    for ax, target in zip(axes, ("entries", "exits")):
        d = res[(res.target == target) & (res.horizon == 1)]
        ax.bar(d.features, d.MAE, color=["#9aa5b1", "#5b8def", "#f2a541", "#2e9e6a"][:len(d)])
        for i, v in enumerate(d.MAE):
            ax.text(i, v, f"{v:.1f}", ha="center", va="bottom", fontsize=9)
        ax.set_ylim(d.MAE.min() * 0.9, d.MAE.max() * 1.03)
        ax.set_title(f"t+1 {'進站' if target == 'entries' else '出站'} MAE")
    fig.suptitle("空間特徵消融（測試集 2026-09）")
    fig.savefig(FIGURES / "spatial_ablation.png", dpi=150)


if __name__ == "__main__":
    main()
