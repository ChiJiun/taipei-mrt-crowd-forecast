"""Spatial features (neighbouring / up- & down-stream stations, OD-flow weighted arrivals) and the
LightGBM-scaled ablation for t+1 (and t+2) entries / exits.

Usage
  python src/41_spatial_features.py            # full ablation (h=1 four variants, h=2 base vs all)
  python src/41_spatial_features.py --quick    # h=1 base vs all only
Outputs
  data/external/station_line_seq.csv  line, line_name, seq, station(physical), panel_stations, n_lines, is_transfer
  results/spatial_ablation.csv, results/spatial_ablation.md
  results/spatial_importance_h1_{target}.csv
  figures/spatial_ablation.png

Spatial features, all observed at the forecast origin t (no look-ahead):
  nb0_total       entries+exits of panel "twins" at the same physical station (景安/O景安 ...)
  nb1_* / nb2_*   sum of entries / exits at stations 1 hop / exactly 2 hops away on the line graph
                  (same-line up- and down-stream stations; transfers link lines), *_l1 = at t-1,
                  *_anom = observed / historical average (station x day type x hour, train only)
  line_*          all stations on the same line(s); net_* whole network
  od_exp_t        sum_o entries_o(t) * p(o->d | hour(t)) : arrivals at d generated by trips that
                  entered the network during hour t, p estimated from training months only
  od_exp_next     sum_o [a_o(t) * HA_o(t+h)] * p(o->d | hour(t+h)) : expected arrivals for the target
                  hour, where a_o(t) = entries_o(t) / HA_o(t) is each origin's current anomaly
  od_ratio_t      exits_d(t) / od_exp_t (destination-specific surplus, e.g. events)
NB the open OD data only has the entry hour, so exits(t) are trips entering in hour t; the "already
on the train" flow for the next physical hour is therefore inside exits(t), and od_exp_next is the
OD-propagated forecast of who will enter elsewhere in t+h and travel to d.
"""
